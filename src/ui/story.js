/**
 * 解析剧情模式的第 index 个场景（纯函数，便于测试）。
 *
 * 场景要么是「读一段档案正文」（可用 `upto` / `from` 把一章拆成战斗前后两段，
 * ★★ 也可以用 **`parts`** 读**不连续的好几段**：`parts: [[from, upto], …]`，与 `from`/`upto`
 * 同一套**半开区间**口径，按给的顺序拼接——第八章"中间＝第 3 段＋第 5 段、战后＝第 4 段＋第 6 段"
 * 就是靠它；没写 `parts` 时老写法逐值不变），
 * 要么是「打一场」。返回值里 `button.action` 决定按钮做什么：
 *   'battle' 下一场是战斗 / 'next' 还有下一个场景 / 'end' 本章结束。
 *
 * ★★ 2026-10-03（第八章改成两阶段）：**一章可以有不止一场战斗**，每一场带自己的阵容与机制。
 *   所以 `view` 里还多带两样"这一幕该用谁、按什么规则打"的东西，让界面不必去猜：
 *   · `lineup`＝这一幕的阵容（`{ player, ally?, enemy, enemy2? }`）——战斗幕读它自己的 `lineup`，
 *     **读剧情的那几幕读"它后面那一场"的**（于是战前那页写的就是即将上场的那套人马）；
 *   · `specialRules`＝同样口径的「本关规则」（战斗幕用自己的，读剧情的那几幕用后面那一场的）。
 *   ⚠️ 老章节一个 `lineup` 都没写 → 全部退回 `chapter.player` / `chapter.enemy`，
 *      与改动前逐字相同。真值判断一律用 `kind === 'battle'`，不再假设"一章只有一场"。
 */
export function storySceneAt(chapter, index) {
  const scenes = chapter?.scenes || [];
  const scene = scenes[index];
  if (!scene) return null;
  const nextIndex = index + 1 < scenes.length ? index + 1 : -1;
  // "这一幕该用谁"：战斗幕是自己；读剧情的那几幕**看后面那一场**（本章没有下一场时退回章节默认）。
  const battleAt = scene.kind === 'battle' ? index : storyBattleScene(chapter, index);
  const battleScene = battleAt >= 0 ? scenes[battleAt] : null;
  const lineup = { player: chapter?.player, enemy: chapter?.enemy, ...(battleScene?.lineup || {}) };
  const specialRules = battleScene?.specialRules || chapter?.specialRules || [];
  if (scene.kind === 'battle') {
    return { index, isBattle: true, note: scene.note || '', paragraphs: [], title: '',
      lineup, specialRules,
      button: { label: '开战', action: 'battle' }, nextIndex };
  }
  const source = STORY.find(item => item.id === scene.readId);
  if (!source) return null;
  // ★★ 2026-10-03 第四条：一幕读到的段落可以是**不连续**的（第八章"中间"＝第 3 段 ＋ 第 5 段，
  //    "战后"＝第 4 段 ＋ 第 6 段——因为阿布德尔的死就发生在阶段 1 之后，第 5 段得跟着第 3 段走）。
  //    所以支持 `parts: [[from, upto], …]`（与 `from`/`upto` 同一种**半开区间**口径，按给的顺序拼接）。
  //    ⚠️ 没写 `parts` 时下面这条老路子**逐值不变**（老章节一个字都不用改）。
  const clamp = value => Math.max(0, Math.min(source.paragraphs.length, Number(value) || 0));
  const parts = Array.isArray(scene.parts) && scene.parts.length
    ? scene.parts.map(([from, upto]) => [clamp(from), clamp(upto)]).filter(([from, upto]) => from < upto)
    : null;
  const from = clamp(scene.from);
  const upto = scene.upto == null ? source.paragraphs.length : clamp(scene.upto);
  const nextIsBattle = scenes[index + 1]?.kind === 'battle';
  const button = nextIsBattle ? { label: '开始对决', action: 'battle' }
    : nextIndex >= 0 ? { label: '继续', action: 'next' }
      : { label: '完成本章', action: 'end' };
  return {
    index, isBattle: false, note: scene.note || '',
    title: source.title, range: source.chapters,
    // `parts` 给的每一段都取一次、按给的顺序拼起来；老写法就是一次 `slice(from, upto)`。
    paragraphs: parts
      ? parts.flatMap(([a, b]) => source.paragraphs.slice(a, b))
      : source.paragraphs.slice(from, upto),
    parts: parts || [[from, upto]],
    lineup, specialRules,
    button, nextIndex,
  };
}

/**
 * 章节里**下一场还没打完的战斗**在第几幕；没有则 -1。
 *
 * ★★ 2026-10-03：第八章改成了两阶段（`scenes` 里有两个 `{kind:'battle'}`），
 *   所以这里**不能再假设"一章只有一场"**——旧的写法是 `findIndex(kind==='battle')`，
 *   它永远只会指回**第一场**，于是第二场打完以后结算页会算错下一幕（甚至被误判成"本章完成"）。
 * `from` 是"已经演到第几幕了"（＝当前的场景光标）：从它往下找第一场战斗，
 * 于是"第一场打完、接着演中间正文、再开第二场"这条链路每一步都算得对。
 * 一章只有一场的老章节：`from` 传 0 或任意 ≤ 那一场的位置，结果与改动前完全一样。
 */
export function storyBattleScene(chapter, from = 0) {
  const scenes = chapter?.scenes || [];
  const start = Math.max(0, Number(from) || 0);
  return scenes.findIndex((scene, index) => index >= start && scene.kind === 'battle');
}

const CN_DIGITS = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
/** 1–99 的中文数字（章节列表用「第一章 / 第二十七章」这种写法）。 */
export function cnNumber(value) {
  const n = Math.max(1, Math.round(Number(value) || 1));
  if (n < 10) return CN_DIGITS[n];
  if (n === 10) return '十';
  if (n < 20) return `十${CN_DIGITS[n - 10]}`;
  if (n % 10 === 0) return `${CN_DIGITS[Math.floor(n / 10)]}十`;
  return `${CN_DIGITS[Math.floor(n / 10)]}十${CN_DIGITS[n % 10]}`;
}

/** 一个剧情章节读到的档案章节所覆盖的话数区间，例如「第 1–8 话」。 */
function chapterRange(chapter) {
  const arcs = (chapter.scenes || []).filter(scene => scene.kind === 'read')
    .map(scene => STORY.find(item => item.id === scene.readId)).filter(Boolean);
  if (!arcs.length) return '';
  const bound = (text, index) => Number(text.match(/^第 (\d+)–(\d+) 话/)[index]);
  return `第 ${bound(arcs[0].chapters, 1)}–${bound(arcs.at(-1).chapters, 2)} 话`;
}

/**
 * 剧情模式的章节路线图（纯函数，便于测试）：
 * 已做成章节的排在前面（可进入），《剧情档案》里还没做成章节的故事弧跟在后面（未解锁）。
 * 以后每实现一章，对应的故事弧就会自动从「未解锁」变成「可进入」，不用手改这张表。
 */
export function storyRoadmap() {
  const covered = new Set();
  for (const chapter of STORY_CHAPTERS) {
    for (const scene of chapter.scenes || []) if (scene.kind === 'read') covered.add(scene.readId);
  }
  const rows = STORY_CHAPTERS.map((chapter, chapterIndex) => ({
    kind: 'chapter', chapterIndex, chapterId: chapter.id,
    title: chapter.title, range: chapterRange(chapter), playable: true,
  }));
  for (const arc of STORY) {
    if (covered.has(arc.id)) continue;
    rows.push({ kind: 'arc', chapterIndex: -1, chapterId: arc.id, title: arc.title,
      range: (arc.chapters.match(/^第 \d+–\d+ 话/) || [arc.chapters])[0], playable: false });
  }
  return rows.map((row, index) => ({ ...row, index, label: `第${cnNumber(index + 1)}章` }));
}

