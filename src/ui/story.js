/**
 * 翻页状态（纯函数，便于单元测试）：把任意页码夹到合法范围，算出这一页要显示什么。
 * main.js 只把这个结果贴到界面上，逻辑本身在这里，测试不需要 DOM。
 */
export function storyPageState(index) {
  const total = STORY.length;
  const numeric = Number(index);
  const wanted = Number.isFinite(numeric) ? Math.trunc(numeric) : 0;
  const current = Math.max(0, Math.min(total - 1, wanted));
  const chapter = STORY[current];
  return {
    index: current,
    total,
    chapter,
    title: chapter.title,
    label: `第 ${current + 1} / ${total} 章 · ${chapter.title}`,
    prevDisabled: current === 0,
    nextDisabled: current === total - 1,
  };
}

/**
 * 剧情档案的 HTML（主界面与战场的「剧情」按钮共用）。
 *
 * **一次只显示一章**：28 章全部渲染出来，但只有当前章不带 `hidden`，
 * 由 main.js 的 `showStoryPage()` 负责切换（改 `hidden`、翻页条与目录高亮）。
 * 之所以一次全渲染、而不是每次重建正文：切换时不用重新拼 1.6 万字符的 HTML，
 * 章节锚点也始终存在。
 */
export function storyHtml() {
  const toc = STORY.map((chapter, index) =>
    `<button type="button" data-story-jump="${chapter.id}" data-story-index="${index}"` +
    (index === 0 ? ' class="is-current" aria-current="true"' : '') +
    `>${chapter.title}</button>`).join('');
  const chapters = STORY.map((chapter, index) =>
    `<article id="story-${chapter.id}" data-story-index="${index}"${index === 0 ? '' : ' hidden'}>` +
    `<b>${chapter.title}</b><small class="story-range">${chapter.chapters}</small>` +
    `${chapter.paragraphs.map(text => `<p>${text}</p>`).join('')}</article>`).join('');
  const pager =
    `<div class="story-pager">` +
    `<button type="button" class="btn" data-story-page="-1">上一章</button>` +
    `<span class="story-position" data-story-position aria-live="polite">${storyPageState(0).label}</span>` +
    `<button type="button" class="btn" data-story-page="1">下一章</button>` +
    `</div>`;
  return `<p class="dialog-lead">${STORY_NOTE}</p>` +
    `<nav class="story-toc" aria-label="章节目录">${toc}</nav>` +
    `${pager}<div class="story-list">${chapters}</div>`;
}

