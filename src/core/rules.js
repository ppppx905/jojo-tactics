/**
 * 把地图数据里的 `items` 收敛成一份**完整的规则**（认不出的键一律剔掉，**绝不抛错**）：
 *   · `items: null` / `false` / `{ enabled: false }` → **这张图没有道具**（一行关掉）；
 *   · 没写 `items` → 用默认那一套（与 `default` / `shallows` 相同）；
 *   · 写了对象 → 逐字段覆盖默认值（`weights` 也一样，逐种类覆盖）。
 * ⚠️ **唯一口径**：`game.js` 的 `Game.itemRule()` 调它，别在别处再解一遍。
 */
export function resolveItemRule(map) {
  const data = map?.items;
  if (data === null || data === false) return null;
  const raw = data && typeof data === 'object' ? data : {};
  if (raw.enabled === false) return null;
  const rule = { ...ITEM_RULE, ...raw };
  // 种类权重：只认 ITEM_TYPES 里真的有的键，而且权重要是正数（"一个都不刷"是合法结果，不是错误）
  rule.weights = Object.fromEntries(Object.entries({ ...ITEM_RULE.weights, ...(raw.weights || {}) })
    .filter(([type, weight]) => ITEM_TYPES[type] && Number.isFinite(weight) && weight > 0));
  return rule;
}

