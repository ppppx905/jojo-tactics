/**
 * 某张地图的**居中甲板矩形**（`{ colStart, colEnd, rowStart, rowEnd }`），没有水域地图就是 `null`。
 * ⚠️ **唯一口径**：`SEA_DECK` 与 `game.js` 的 `Game.deckRect()` 都调它，别在别处再算一遍居中。
 * ★ 2026-10-05（棋盘 14×11 → 18×13）：起止行列**跟着棋盘重新居中**——由 COLS/ROWS 算出来，不写死。
 * ★★ 2026-10-05（本次改动）：浅滩水路的甲板从"正中一小块 4×5 = 20 格"改成
 *   **"横跨左右全宽的一条带子"（`cols: COLS`、`rows: 3`）**，于是这里算出来的是：
 *     · 列：`(18 − 18) / 2 = 0` → 第 0~17 列（**整行全宽**）
 *     · 行：`(13 − 3) / 2 = 5` → 第 5~7 行（**垂直居中**，正中那一行就是 `MID_ROW` = 6）
 *   共 18 × 3 = **54 格**。算式一个字没改（仍然是"居中"这一条），只改了地图数据里的尺寸。
 *   ⚠️ 因此"甲板在正中央"这件事既有纵向口径（`rowStart + rowEnd === ROWS − 1`），
 *      也有横向口径（`colStart + colEnd === COLS − 1`）——两条都还在，见测试。
 */
export function deckRectOf(map) {
  const deck = map?.features?.water?.deck;
  if (!deck || !(deck.cols > 0) || !(deck.rows > 0)) return null;
  const colStart = (COLS - deck.cols) / 2, rowStart = (ROWS - deck.rows) / 2;
  return { colStart, colEnd: colStart + deck.cols - 1, rowStart, rowEnd: rowStart + deck.rows - 1 };
}
